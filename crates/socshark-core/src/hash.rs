//! SHA-256 propio (FIPS 180-4), sin dependencias externas (ADR-011).
//!
//! Se introdujo en la Fase 3 para las huellas JA4 y se reutiliza desde la
//! Fase 4 para el hashing de archivos extraídos (file carving). No es una
//! primitiva de seguridad en uso: es una función de resumen determinista y
//! pública sobre datos ya observados; por eso se implementa aquí en ~80
//! líneas en lugar de arrastrar una dependencia criptográfica.

